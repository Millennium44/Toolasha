/** Names accepted by buildLabyrinthUpdated, in the order a run goes through them */
export const LABYRINTH_UPDATED_NAMES = Object.keys(LABYRINTH_UPDATED);

/**
 * @param {string} name - One of LABYRINTH_UPDATED_NAMES
 * @param {Object} [overrides] - Fields replaced on the inner `labyrinth` object
 * @returns {Object} A `labyrinth_updated` message (a fresh copy each call)
 */
export function buildLabyrinthUpdated(name, overrides = {}) {
    const base = structuredClone(LABYRINTH_UPDATED[name]);
    if (!base) throw new Error(`No labyrinth_updated fixture named ${name}`);
    return { ...base, labyrinth: { ...base.labyrinth, ...overrides } };
}

/**
 * @param {'first'|'afterOneAction'|'last'} [which] - Start of a room, after one action, or late in a hard room
 * @returns {Object} A `labyrinth_room_progress` message (a fresh copy each call)
 */
export function buildLabyrinthRoomProgress(which = 'first') {
    return structuredClone(LABYRINTH_ROOM_PROGRESS[which]);
}

/**
 * @param {Object} [overrides] - Fields replaced on the message
 * @returns {Object} A `new_battle` message for a labyrinth combat room (a fresh copy each call)
 */
export function buildLabyrinthNewBattle(overrides = {}) {
    return { ...structuredClone(LABYRINTH_NEW_BATTLE), ...overrides };
}

/** @returns {Object[]} The `info` notices the party flow produced (a fresh copy each call) */
export function buildInfoNotices() {
    return structuredClone(INFO_NOTICES);
}
